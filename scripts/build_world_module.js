/* Generate lessons and labs from one canonical executable model per chapter. */
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const context = {window: {}};
vm.runInNewContext(fs.readFileSync(path.join(root, 'assets/js/world-models.js'), 'utf8'), context);
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'lessons/world/manifest.json'), 'utf8'));
function example(c) {
  return '```javascript\n' + context.window.HUB_WORLD_MODELS[c.model].toString() + '\n\nconst scenario = ' + JSON.stringify(c.defaults, null, 2) + ';\nconst result = simulate(scenario);\nconsole.log(JSON.stringify(result.summary, null, 2));\n```';
}
const chapters = catalog.map(c => {
  let content = fs.readFileSync(path.join(root, 'lessons/world', c.id + '.md'), 'utf8').replace(/\r\n?/g, '\n');
  if (!content.includes('<!-- world-code -->')) throw Error('Missing code marker: ' + c.id);
  content = content.replace('<!-- world-code -->', example(c));
  (c.extraLabs || []).forEach(extra => {
    const marker = '<!-- world-code:' + extra.model + ' -->';
    if (!content.includes(marker) || !content.includes('```demo:world-' + extra.model)) throw Error('Missing supplementary code/lab: ' + extra.model);
    content = content.replace(marker, example(extra));
  });
  if (!content.includes('```demo:world-' + c.model)) throw Error('Missing lab: ' + c.id);
  return {id:c.id, title:c.title, minutes:c.minutes, points: c.points || [c.actual, '网页实验', '原理与边界'], content,
    practice: {task:c.task, checks:['先写下两组输入的预测，再运行', '记录实际结果、对应代码条件及反例', '说明模型省略的物理条件与结论边界'], answer:c.answer}};
});
const moduleData = {id:'world', title:'编程与真实世界', en:'LIFE · SPACE · CIVILIZATION', icon:'spark', color:'#38bdf8', tagline:'从一次心跳，到宇宙中的文明记忆', description:'14 章深入连接代码与医疗、航空航天、外星生命探索和文明传承。沿着调查报告拆解千年虫、阿丽亚娜 501、火星轨道器等案例，用可调参数、逐步高亮与图形实验理解每一步因果；所有示例直接在网页虚拟环境运行。', minutes:'≈ 14 小时（含实验）', chapters};
const labs = catalog.flatMap(c => [c, ...(c.extraLabs || [])]);
fs.writeFileSync(path.join(root,'assets/js/world-catalog.js'), '/* Generated by scripts/build_world_module.js. */\nwindow.HUB_WORLD_CATALOG = ' + JSON.stringify(labs, null, 2) + ';\n');
fs.writeFileSync(path.join(root,'assets/js/content/world.js'), '/* Generated from lessons/world/*.md and the shared models. */\nwindow.CONTENT = window.CONTENT || {};\nwindow.CONTENT.world = ' + JSON.stringify(moduleData, null, 2) + ';\n');
console.log('World module:', chapters.length, 'chapters,', chapters.reduce((n,c)=>n+c.content.length,0), 'characters');
